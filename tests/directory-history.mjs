import assert from 'node:assert/strict';
import fs from 'node:fs';
const values=new Map();let rejectWrites=false;
const database={transaction(){const tx={objectStore(){return {get(key){const r={};queueMicrotask(()=>{r.result=values.get(key);r.onsuccess();});return r;},delete(key){queueMicrotask(()=>{values.delete(key);tx.oncomplete();});},put(value,key){queueMicrotask(()=>{if(rejectWrites){tx.error=Error('disk full');tx.onerror();}else{values.set(key,value);tx.oncomplete();}});}};}};return tx;}};
globalThis.indexedDB={open(){const r={};queueMicrotask(()=>{r.result=database;r.onsuccess();});return r;}};
const source=fs.readFileSync(new URL('../files.js',import.meta.url),'utf8');
const {loadDirectoryCaseHistory,saveDirectoryCaseHistory,loadCaseHistory,saveCaseHistory,loadCaseLibraries,caseLibraryDirectory,saveDirectory,loadDirectory,replaceCaseLibraryDirectory,removeCaseLibrary}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const folder=id=>({name:'素材',id,async isSameEntry(other){return other.id===id;}});
assert.equal(await loadDirectoryCaseHistory(folder('a')),undefined);
await saveDirectoryCaseHistory(folder('a'),[{title:'A'}]);
assert.equal((await loadDirectoryCaseHistory(folder('a')))[0].title,'A','reselected handle reuses history');
assert.equal(await loadDirectoryCaseHistory(folder('b')),undefined,'same folder name does not share history');
await saveDirectoryCaseHistory(folder('b'),[{title:'B'}]);
assert.equal((await loadDirectoryCaseHistory(folder('a')))[0].title,'A');
await saveCaseHistory([{title:'default'}]);assert.equal((await loadCaseHistory())[0].title,'default');
assert.equal((await loadDirectoryCaseHistory(folder('b')))[0].title,'B','default downloads stay separate');
rejectWrites=true;await assert.rejects(saveDirectoryCaseHistory(folder('a'),[]),/disk full/);
assert.equal((await loadDirectoryCaseHistory(folder('a')))[0].title,'A','failed save retains old history');
console.log('PASS: internal index persistence, folder identity, independent libraries, default history isolation, write failure');
const libraries=await loadCaseLibraries();assert.equal(libraries.length,3);
assert.deepEqual(libraries.flatMap(l=>l.records.map(r=>r.title)),['default','A','B']);
assert.equal((await caseLibraryDirectory(libraries[1].key)).id,'a');
assert.equal(await caseLibraryDirectory('case-history'),null);
await assert.rejects(caseLibraryDirectory('missing'),/找不到/);
console.log('PASS: global history aggregation, original directory lookup, missing directory');
rejectWrites=false;
await saveDirectory(folder('a'));
await replaceCaseLibraryDirectory(libraries[1].key,folder('moved-a'));
assert.equal((await loadDirectory()).id,'moved-a','relink must update the active download directory');
assert.equal((await caseLibraryDirectory(libraries[1].key)).id,'moved-a');
assert.equal((await loadDirectoryCaseHistory(folder('moved-a')))[0].title,'A','relink keeps existing history');
await replaceCaseLibraryDirectory(libraries[2].key,folder('moved-b'));
assert.equal((await loadDirectory()).id,'moved-a','relinking another library must not change download destination');
console.log('PASS: relinking synchronizes active download handle and preserves unrelated destination');
await removeCaseLibrary(libraries[2].key);
assert.equal((await loadCaseLibraries()).length,2);
assert.equal((await loadDirectory()).id,'moved-a','removing another root preserves active save folder');
assert.equal(values.has(libraries[2].key),false,'remove forgotten history');
await removeCaseLibrary(libraries[1].key);
assert.equal(await loadDirectory(),null,'removed active root must not be silently re-added on next download');
assert.equal((await loadCaseHistory())[0].title,'default');
console.log('PASS: remove library clears registry and index without touching filesystem');
