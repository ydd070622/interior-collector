import assert from 'node:assert/strict';
import fs from 'node:fs';
const encode=code=>'data:text/javascript;base64,'+Buffer.from(code).toString('base64');
const adapters=await import(encode(fs.readFileSync(new URL('../site-adapters.js',import.meta.url),'utf8')));
const {getSiteAdapter,isLargeImage}=adapters;
assert.equal(getSiteAdapter('https://www.xiaohongshu.com/explore/a').id,'xiaohongshu');
assert.equal(getSiteAdapter('https://xiaohongshu.com.evil.test').id,'generic');
assert.equal(getSiteAdapter('https://www.google.co.uk/search?tbm=isch').id,'google-images');
assert.equal(getSiteAdapter('https://www.bing.com/images/search').id,'bing-images');
assert.equal(getSiteAdapter('https://shop.example.com/item/123').id,'generic');
assert.equal(isLargeImage(800,600),true);assert.equal(isLargeImage(400,1000),true);assert.equal(isLargeImage(800,8000),true);assert.equal(isLargeImage(150,5000),false);assert.equal(isLargeImage(300,300),false);
const source=fs.readFileSync(new URL('../image-candidates.js',import.meta.url),'utf8').replace(/^import .*;\r?\n/gm,'');
globalThis.__largeTest={...adapters};
const {prepareLargeImage}=await import(encode('const {isLargeImage}=globalThis.__largeTest;const fetchImage=()=>{},thumbnail=()=>{},fingerprint=async()=>({});\n'+source));
let closed=0;
const options={fetch:async url=>{if(url==='bad')throw Error('404');const [width,height]=url.split('x').map(Number);return {bitmap:{width,height,close(){closed++;}}};},makeThumbnail:async()=>new Blob()};
let result=await prepareLargeImage({url:'bad',urls:['200x200','800x1200','1080x1600']},options);
assert.equal(result.url,'1080x1600');assert.equal(closed,3,'all decoded bitmaps close');
result=await prepareLargeImage({url:'200x200'},options);assert.equal(result.excluded,true);
result=await prepareLargeImage({url:'bad'},options);assert.equal(result.error,'404');
result=await prepareLargeImage({url:'800x8000'},options);assert.equal(result.height,8000);
console.log('PASS: adapter dispatch, strict default large images, meaningful long images, original alternatives, largest decoded version, failed originals and bitmap cleanup');
