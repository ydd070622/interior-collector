import assert from 'node:assert/strict';
import fs from 'node:fs';
const source=fs.readFileSync(new URL('../note-paths.js',import.meta.url),'utf8');
const {safeTitle,openNoteDirectory,imageSavePath}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
assert.equal(safeTitle('标题\u200b\u0000'),'标题');
assert.equal(safeTitle('标题. '),'标题');
assert.equal(safeTitle('甲/乙:丙'),'甲_乙_丙');
const calls=[];const handle={kind:'directory'};
const destination={async getDirectoryHandle(name){calls.push(name);if(name.includes('🤷')||name.endsWith('。'))throw new TypeError('Name is not allowed.');return handle;}};
const folders=new Map([['note','09-🤷淡人的家，干净就好。']]);
const opened=await openNoteDirectory(destination,folders.get('note'),folders,'note');
assert.equal(opened.folder,'09-淡人的家干净就好');
assert.equal(opened.directory,handle);
assert.equal(folders.get('note'),opened.folder);
const item={noteId:'note',noteTitle:'🤷淡人的家，干净就好。',imageIndex:1};
assert.equal(imageSavePath(item,[item],'png',folders).folder,opened.folder);
assert.equal((await openNoteDirectory(destination,opened.folder,folders,'note')).folder,opened.folder);
assert.equal(calls.length,3);
const denied={async getDirectoryHandle(){throw new DOMException('Permission denied','NotAllowedError');}};
await assert.rejects(openNoteDirectory(denied,'01-标题',folders,'note'),{name:'NotAllowedError'});
console.log('PASS: invisible characters, invalid-name fallback, stable folder for subsequent images, permission errors preserved');
